/**
 * Discover and rank shelters for a given station/incident coordinate
 */
export function discoverNearbyShelters(
  stationId: string,
  userLat?: number,
  userLon?: number,
): ReliefShelter[] {
  const directMatches = VERIFIED_RELIEF_SHELTERS.filter((s) => s.stationId === stationId);
  if (directMatches.length > 0) return directMatches;

  // Fallback to spatial proximity if user coordinates provided
  if (userLat !== undefined && userLon !== undefined) {
    return [...VERIFIED_RELIEF_SHELTERS]
      .map((s) => ({
        ...s,
        distanceFromStationKm: Math.round(haversineDistanceKm(userLat, userLon, s.coordinates.lat, s.coordinates.lon) * 10) / 10,
      }))
      .sort((a, b) => a.distanceFromStationKm - b.distanceFromStationKm);
  }

  return VERIFIED_RELIEF_SHELTERS.slice(0, 2);
}

/**
 * Get available evacuation routes for an incident station
 */
export function getEvacuationRoutesForStation(stationId: string): EvacuationRoute[] {
  const stationRoutes = VERIFIED_EVACUATION_ROUTES.filter((r) => r.stationId === stationId);
  if (stationRoutes.length > 0) {
    return stationRoutes;
  }
  return VERIFIED_EVACUATION_ROUTES.slice(0, 2);
}
